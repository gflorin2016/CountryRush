const norm = s => s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
// Aliases of 1-2 letters (ma, si, no, de, in, is ...) are ordinary chat words, so they are ignored (only "uk" is kept).
const MATCHERS = COUNTRIES.map(c => ({
  ...c,
  als: [...new Set(c.aliases.map(norm))]
    .filter(a => a.length >= 3 || a === "uk")
    .map(a => ({ a, re: new RegExp(`(^|[^a-z0-9])${a.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}([^a-z0-9]|$)`, "i") })),
}));

// The longest alias found in the message wins ("africa de sud" -> South Africa, not "de").
export function matchCountry(text) {
  const t = norm(String(text || ""));
  let best = null, bl = 0;
  for (const m of MATCHERS) for (const x of m.als) if (x.a.length > bl && x.re.test(t)) { best = m; bl = x.a.length; }
  return best;
}
